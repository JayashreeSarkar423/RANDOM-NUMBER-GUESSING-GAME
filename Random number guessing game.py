import random
n=random.randint(1,10)
while True:
  a=int(input("enter the number guessed: "))
  if (a==n):
    print("correct num guessed")
    break
  else:
    if(a<n):
      print("higher number to be guessed")
    elif(a>n):
      print("lower number to be guessed")
     
  

                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                 
  
    
    
  
